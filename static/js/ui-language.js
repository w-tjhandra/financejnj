  function translateText(original, language) {
    var dictionary = translations[language];
    if (!dictionary) {
      return original;
    }
    var trimmed = original.replace(/\s+/g, " ").trim();
    if (dictionary[trimmed]) {
      return original.replace(trimmed, dictionary[trimmed]);
    }
    var translated = trimmed;
    if (language !== "id") {
      translated = translated.replace(/\bRp(?=\s*[-\d.,])/g, "IDR");
    }
    Object.keys(dictionary)
      .sort(function (left, right) {
        return right.length - left.length;
      })
      .forEach(function (source) {
        if (source.length < 4 || translated.toLowerCase().indexOf(source.toLowerCase()) === -1) {
          return;
        }
        var escaped = source.replace(/[.*+?^${}()|[\]\\]/g, "\\$&").replace(/\s+/g, "\\s+");
        var expression = new RegExp("(^|[^A-Za-z0-9])(" + escaped + ")(?=$|[^A-Za-z0-9])", "gi");
        translated = translated.replace(expression, function (match, prefix, phrase) {
          var replacement = dictionary[phrase] || dictionary[source];
          if (phrase === phrase.toLowerCase()) {
            replacement = replacement.charAt(0).toLowerCase() + replacement.slice(1);
          }
          return prefix + replacement;
        });
      });
    if (language === "en") {
      translated = translated.replace(/\b1 transactions\b/g, "1 transaction");
      translated = translated.replace(/\b1 times\b/g, "1 time");
    } else if (language === "ko") {
      translated = translated.replace(/(\d+) 회(?=$|[^A-Za-z0-9])/g, "$1회");
    }
    if (translated !== trimmed) {
      var leading = original.match(/^\s*/)[0];
      var trailing = original.match(/\s*$/)[0];
      return leading + translated + trailing;
    }
    return original;
  }

  function translateNode(node, language) {
    node.nodeValue = translateText(node.nodeValue, language);
  }

  function translateTree(root, language) {
    if (!translations[language]) {
      return;
    }
    var walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
      acceptNode: function (node) {
        var parent = node.parentElement;
        if (!parent || /^(SCRIPT|STYLE|TEXTAREA|INPUT|SELECT)$/i.test(parent.tagName)) {
          return NodeFilter.FILTER_REJECT;
        }
        return NodeFilter.FILTER_ACCEPT;
      },
    });
    while (walker.nextNode()) {
      translateNode(walker.currentNode, language);
    }
    var translatableAttributes = "input, select, textarea, button, a, [onsubmit], [onclick]";
    if (root.nodeType === Node.ELEMENT_NODE && root.matches(translatableAttributes)) {
      translateAttributes(root, language);
    }
    root.querySelectorAll(translatableAttributes).forEach(function (element) {
      translateAttributes(element, language);
    });
  }

  function translateAttributes(element, language) {
    ["aria-label", "placeholder", "title", "alt", "onsubmit", "onclick"].forEach(function (attribute) {
      var value = element.getAttribute(attribute);
      if (value) {
        var translated = translateText(value, language);
        if (translated !== value) {
          element.setAttribute(attribute, translated);
        }
      }
    });
    if (/^(submit|button|reset)$/i.test(element.type || "")) {
      var value = element.value;
      var translated = value && translations[language][value.trim()];
      if (translated) {
        element.value = value.replace(value.trim(), translated);
      }
    }
  }

  var language = document.documentElement.lang;
  window.TelurFinanceTranslations = {
    language: language,
    text: function (value) {
      return translateText(value, language);
    },
  };

  document.addEventListener("DOMContentLoaded", function () {
    translateTree(document.body, language);
    translateTree(document.head, language);
  });
  document.body.addEventListener("htmx:afterSwap", function (event) {
    translateTree(event.detail.target, language);
  });
  var observer = new MutationObserver(function (mutations) {
    mutations.forEach(function (mutation) {
      if (mutation.type === "characterData") {
        translateNode(mutation.target, language);
      }
      mutation.addedNodes.forEach(function (node) {
        if (node.nodeType === Node.TEXT_NODE) {
          translateNode(node, language);
        } else if (node.nodeType === Node.ELEMENT_NODE) {
          translateTree(node, language);
        }
      });
    });
  });
  document.addEventListener("DOMContentLoaded", function () {
    observer.observe(document.body, { childList: true, characterData: true, subtree: true });
  });
